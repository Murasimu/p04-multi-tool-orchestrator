"""Demo: plan + execute a workflow over a fictional e-commerce back office.

Scenario (all data fictional): "Prepare the weekly sales summary: pull
inventory and orders, then generate the report and email it."

Shows:
1. LLM plans the workflow as a tool DAG
2. Permission scoping (a viewer role gets denied the email step)
3. Parallel reads run concurrently (timed)
4. Same-resource writers are serialized (conflict resolution log)

Usage:
  python demo.py            # scripted planner, no network
  python demo.py --live     # live LLM planning
"""

from __future__ import annotations

import sys
import time

from orchestrator import Orchestrator, Planner, Plan, PlanStep, PolicyDB, Role, ToolRegistry, ToolSpec


# ---- fictional back office -----------------------------------------
LOG: list[tuple[str, float]] = []
LOCK = __import__("threading").Lock()


def log_call(name):
    def fn(args):
        time.sleep(0.15 if name.startswith("pull") else 0.02)
        with LOCK:
            LOG.append((name, time.time()))
        return {"tool": name, "args": args, "ok": True}
    return fn


def build_registry():
    r = ToolRegistry()
    specs = [
        ("pull_inventory", "Pull current inventory levels", "read:inventory", "db.inventory", True),
        ("pull_orders", "Pull last 7 days of orders", "read:orders", "db.orders", True),
        ("pull_shipments", "Pull shipment statuses", "read:shipments", "db.shipments", True),
        ("gen_report", "Generate the weekly sales report", "write:reports", "db.reports", True),
        ("archive_report", "Archive the report", "write:reports", "db.reports", True),
        ("send_email", "Email the report to stakeholders", "write:email", "smtp.outbound", True),
        ("audit_log", "Write an audit entry", "write:audit", "db.audit", True),
        ("audit_log2", "Write a second audit entry", "write:audit2", "db.audit", True),
    ]
    for name, desc, cap, res, par in specs:
        r.register(ToolSpec(name, desc, log_call(name), (cap,), (res,), par))
    return r


def build_policies():
    p = PolicyDB()
    p.add_role(Role("viewer", ("read:*",)))
    p.add_role(Role("operator", ("read:*", "write:reports")))
    p.add_role(Role("admin", ("*",)))
    return p


def show_report(report, label):
    print(f"\n--- {label} ---")
    print(f"ok={report.ok}  steps={report.plan_steps}  stages={report.stages}")
    for o in report.outcomes:
        line = f"  [{o.status:7}] stage={o.stage} {o.name:16} ({o.tool}) {o.seconds:.2f}s"
        if o.error:
            line += f"  err={o.error[:70]}"
        print(line)
    for c in report.conflicts_resolved:
        print(f"  [conflict] {c.step_a} <-> {c.step_b} on {c.resource} ({c.reason}) -> serialized")


SCRIPTED_PLAN = """[
  {"name": "inv",   "tool": "pull_inventory", "args": {"region": "all"}},
  {"name": "ords",  "tool": "pull_orders",    "args": {"days": 7}},
  {"name": "ships", "tool": "pull_shipments", "args": {"days": 7}},
  {"name": "rep",   "tool": "gen_report",     "args": {"kind": "weekly"}, "depends_on": ["inv", "ords", "ships"]},
  {"name": "arch",  "tool": "archive_report", "args": {}, "depends_on": ["rep"]},
  {"name": "mail",  "tool": "send_email",     "args": {"to": "stakeholders"}, "depends_on": ["rep"]},
  {"name": "audit", "tool": "audit_log",      "args": {}, "depends_on": ["rep"]},
  {"name": "audit2","tool": "audit_log2",     "args": {}, "depends_on": ["rep"]}
]"""


def main():
    registry = build_registry()
    policies = build_policies()

    print("=" * 62)
    print("1) Parallel reads: 3x 0.15s pulls should take ~0.15s wall")
    print("=" * 62)
    planner = Planner(registry, llm=lambda m: SCRIPTED_PLAN)
    plan = planner.plan("Prepare the weekly sales summary and email it")
    orch = Orchestrator(registry, policies)
    t0 = time.time()
    report = orch.execute(plan, role="admin")
    wall = time.time() - t0
    show_report(report, "admin run")
    print(f"\nwall time: {wall:.2f}s (serial would be ~0.50s+ for reads alone)")

    print()
    print("=" * 62)
    print("2) Conflict resolution: gen_report vs archive_report both")
    print("   write db.reports -> serialized, logged")
    print("=" * 62)
    print("   (see [conflict] lines above)")

    print()
    print("=" * 62)
    print("3) Permission scoping: viewer role hits the email step")
    print("=" * 62)
    LOG.clear()
    orch2 = Orchestrator(registry, policies)
    report2 = orch2.execute(plan, role="viewer")
    show_report(report2, "viewer run")
    denied = [o for o in report2.outcomes if o.status == "denied"]
    print(f"\ndenied steps: {[o.name for o in denied]} (viewer can't write reports or email)")

    if "--live" in sys.argv:
        print()
        print("=" * 62)
        print("4) Live LLM planning (same task, plan generated by the model)")
        print("=" * 62)
        from orchestrator.llm import make_llm
        try:
            live = make_llm()
        except RuntimeError as e:
            print(f"skipping live demo: {e}")
            return
        planner3 = Planner(registry, llm=live)
        try:
            plan3 = planner3.plan("Prepare the weekly sales summary and email it to stakeholders")
        except Exception as e:
            print(f"live planner failed validation: {e}")
            return
        print("plan:")
        for s in plan3.steps:
            print(f"  - {s.name:8} {s.tool:18} deps={s.depends_on}")
        LOG.clear()
        report3 = Orchestrator(registry, policies).execute(plan3, role="admin")
        show_report(report3, "live-plan run")


if __name__ == "__main__":
    main()
